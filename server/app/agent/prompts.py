"""Agent 提示词。

为物品识别 Agent 专门设计，与管线的「快速场景判断」提示词区分。
"""

from __future__ import annotations


AGENT_SYSTEM_PROMPT = """你是一个专业的视觉识别助手，擅长分析图像并识别其中的物品。

你的主要能力：
1. **物品识别**：准确识别图像中的各类物品，包括日常用品、家具、电子产品、食物、植物等
2. **场景理解**：分析整体环境，判断场景类型（室内/室外、办公/居家/户外等）
3. **知识增强**：可以检索知识库获取物品的专业信息

回答要求：
- 使用中文回答，物品名称同时提供中英文
- 描述物品位置时使用相对位置（如"画面左侧"、"桌面上"、"背景中"）
- 对于不确定的物品，说明不确定性程度
- 如果用户追问某个物品，提供更详细的信息

当你收到图片时，主动识别所有可见的主要物品。如果用户有特定问题，优先回答问题。
"""


RECOGNIZE_DETAILED_PROMPT = """请仔细分析这张图片，识别所有可见的物品。

对每个物品，请提供：
1. **名称**：中文名称和英文名称
2. **位置**：在画面中的相对位置（左上、中央、右下角等）
3. **数量**：如果是多个同类物品
4. **外观**：颜色、材质、大致尺寸
5. **状态**：物品的当前状态（如：打开/关闭、满/空、新/旧）

请按物品在画面中的显著程度排序，从最明显的开始。

输出格式示例：
```
检测到以下物品：

1. **咖啡杯 (Coffee Mug)**
   - 位置：画面中央偏右，桌面上
   - 外观：白色陶瓷，约 300ml 容量
   - 状态：装有深色液体（疑似咖啡）

2. **笔记本电脑 (Laptop)**
   - 位置：画面左侧
   - 外观：银色金属外壳，约 14 寸
   - 状态：屏幕亮起，显示代码编辑器
```

如果画面中物品较多，优先描述最显眼的 5-8 个物品，其余可简要列出。"""


RECOGNIZE_BRIEF_PROMPT = """请快速列出这张图片中可见的主要物品（3-5 个最显眼的）。

格式：物品名（英文）- 位置

例如：
- 咖啡杯 (Coffee Mug) - 桌面中央
- 笔记本电脑 (Laptop) - 画面左侧
- 盆栽 (Potted Plant) - 右上角窗台"""


SCENE_DESCRIBE_PROMPT = """请描述这张图片的整体场景：

1. **环境类型**：室内/室外、具体场所（办公室、咖啡厅、公园等）
2. **空间布局**：整体空间感和主要区域划分
3. **光线条件**：自然光/人工光、光线强度、是否有阴影
4. **氛围/用途**：这个场景的用途或氛围
5. **注意事项**：如果有任何安全隐患或值得注意的细节

请用自然语言描述，像在给一个无法看到图片的人讲解一样。"""


def build_chat_user_prompt(message: str, has_image: bool) -> str:
    """构建对话用户消息。"""
    if has_image:
        return f"[用户附带了一张图片]\n\n{message}"
    return message


def build_recognize_prompt(detail_level: str) -> str:
    """根据详细程度返回识别提示词。"""
    if detail_level == "brief":
        return RECOGNIZE_BRIEF_PROMPT
    return RECOGNIZE_DETAILED_PROMPT
